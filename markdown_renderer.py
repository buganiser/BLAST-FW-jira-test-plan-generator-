"""
Markdown Renderer - Converts TestPlan objects to IEEE 829 compliant Markdown documents.
"""
import json
from datetime import datetime
from pathlib import Path
from typing import Any

from test_plan_generator import TestPlan, TestItem, TestingTask, RiskContingency, Approval
from config import config


class MarkdownRenderer:
    """Renders TestPlan to IEEE 829 compliant Markdown."""

    def __init__(self, output_config=None):
        self.output_cfg = output_config or config.output
        self.output_dir = Path(self.output_cfg.directory)
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def render(self, test_plan: TestPlan) -> str:
        """Render complete test plan to Markdown string."""
        lines = []

        # Header
        lines.append(f"# Test Plan: {test_plan.identifier.replace('TP-', '')}")
        lines.append("")
        lines.append(f"**Identifier:** {test_plan.identifier}")
        lines.append(f"**Version:** 1.0")
        lines.append(f"**Date:** {datetime.now().strftime('%Y-%m-%d')}")
        lines.append(f"**Author:** Generated by Jira Test Plan Generator")
        lines.append(f"**Status:** Draft")
        lines.append("")

        # Table of Contents
        lines.append("## Table of Contents")
        lines.append("1. [Introduction](#1-introduction)")
        lines.append("2. [Test Items](#2-test-items)")
        lines.append("3. [Features to be Tested](#3-features-to-be-tested)")
        lines.append("4. [Features Not to be Tested](#4-features-not-to-be-tested)")
        lines.append("5. [Approach](#5-approach)")
        lines.append("6. [Pass/Fail Criteria](#6-passfail-criteria)")
        lines.append("7. [Suspension/Resumption Criteria](#7-suspensionresumption-criteria)")
        lines.append("8. [Test Deliverables](#8-test-deliverables)")
        lines.append("9. [Testing Tasks](#9-testing-tasks)")
        lines.append("10. [Environmental Needs](#10-environmental-needs)")
        lines.append("11. [Responsibilities](#11-responsibilities)")
        lines.append("12. [Staffing and Training](#12-staffing-and-training)")
        lines.append("13. [Schedule](#13-schedule)")
        lines.append("14. [Risks and Contingencies](#14-risks-and-contingencies)")
        lines.append("15. [Approvals](#15-approvals)")
        lines.append("")

        # 1. Introduction
        lines.append("## 1. Introduction")
        intro = test_plan.introduction
        lines.append("### 1.1 Purpose")
        lines.append(intro.get("purpose", "TBD"))
        lines.append("")
        lines.append("### 1.2 Scope")
        lines.append(intro.get("scope", "TBD"))
        lines.append("")
        lines.append("### 1.3 References")
        for ref in test_plan.references:
            lines.append(f"- {ref}")
        lines.append("")
        lines.append("### 1.4 Overview")
        lines.append(intro.get("overview", "TBD"))
        lines.append("")

        # 2. Test Items
        lines.append("## 2. Test Items")
        lines.append("")
        if test_plan.test_items:
            lines.append("| ID | Name | Description | Risk Level | References |")
            lines.append("|----|------|-------------|------------|------------|")
            for item in test_plan.test_items:
                refs = ", ".join(item.references) if item.references else "-"
                desc = item.description.replace("|", "\\|").replace("\n", " ")
                lines.append(f"| {item.id} | {item.name} | {desc} | {item.risk_level} | {refs} |")
        else:
            lines.append("*No test items defined.*")
        lines.append("")

        # 3. Features to be Tested
        lines.append("## 3. Features to be Tested")
        lines.append("")
        if test_plan.features_to_test:
            for feature in test_plan.features_to_test:
                lines.append(f"- {feature}")
        else:
            lines.append("*No features specified.*")
        lines.append("")

        # 4. Features Not to be Tested
        lines.append("## 4. Features Not to be Tested")
        lines.append("")
        if test_plan.features_not_to_test:
            for feature in test_plan.features_not_to_test:
                lines.append(f"- {feature}")
        else:
            lines.append("*All features in scope.*")
        lines.append("")

        # 5. Approach
        lines.append("## 5. Approach")
        approach = test_plan.approach
        lines.append("### 5.1 Strategy")
        lines.append(approach.get("strategy", "TBD"))
        lines.append("")
        lines.append("### 5.2 Techniques")
        for tech in approach.get("techniques", []):
            lines.append(f"- {tech}")
        lines.append("")
        lines.append("### 5.3 Tools")
        for tool in approach.get("tools", []):
            lines.append(f"- {tool}")
        lines.append("")
        lines.append("### 5.4 Entry/Exit/Suspension/Resumption Criteria")
        lines.append("")
        lines.append("#### Entry Criteria")
        for ec in approach.get("entry_criteria", []):
            lines.append(f"- {ec}")
        lines.append("")
        lines.append("#### Exit Criteria")
        for ec in approach.get("exit_criteria", []):
            lines.append(f"- {ec}")
        lines.append("")
        lines.append("#### Suspension Criteria")
        for sc in approach.get("suspension_criteria", []):
            lines.append(f"- {sc}")
        lines.append("")
        lines.append("#### Resumption Criteria")
        for rc in approach.get("resumption_criteria", []):
            lines.append(f"- {rc}")
        lines.append("")

        # 6. Pass/Fail Criteria
        lines.append("## 6. Pass/Fail Criteria")
        lines.append("")
        pf = test_plan.pass_fail_criteria
        lines.append("### 6.1 Item Pass Criteria")
        lines.append(pf.get("item_pass_criteria", "TBD"))
        lines.append("")
        lines.append("### 6.2 Plan Pass Criteria")
        lines.append(pf.get("plan_pass_criteria", "TBD"))
        lines.append("")

        # 7. Suspension/Resumption Criteria
        lines.append("## 7. Suspension/Resumption Criteria")
        lines.append("")
        lines.append(test_plan.suspension_resumption or "TBD")
        lines.append("")

        # 8. Test Deliverables
        lines.append("## 8. Test Deliverables")
        lines.append("")
        for deliverable in test_plan.test_deliverables:
            lines.append(f"- {deliverable}")
        lines.append("")

        # 9. Testing Tasks
        lines.append("## 9. Testing Tasks")
        lines.append("")
        if test_plan.testing_tasks:
            lines.append("| ID | Name | Description | Dependencies | Owner | Effort |")
            lines.append("|----|------|-------------|--------------|-------|--------|")
            for task in test_plan.testing_tasks:
                deps = ", ".join(task.dependencies) if task.dependencies else "-"
                desc = task.description.replace("|", "\\|").replace("\n", " ")
                lines.append(f"| {task.id} | {task.name} | {desc} | {deps} | {task.owner} | {task.effort_estimate} |")
        else:
            lines.append("*No testing tasks defined.*")
        lines.append("")

        # 10. Environmental Needs
        lines.append("## 10. Environmental Needs")
        lines.append("")
        env = test_plan.environment
        for category, items in env.items():
            lines.append(f"### 10.{list(env.keys()).index(category)+1} {category.title()}")
            for item in items:
                lines.append(f"- {item}")
            lines.append("")

        # 11. Responsibilities
        lines.append("## 11. Responsibilities")
        lines.append("")
        if test_plan.responsibilities:
            lines.append("| Role | Name | Responsibilities |")
            lines.append("|------|------|------------------|")
            for resp in test_plan.responsibilities:
                resp_list = "; ".join(resp.get("responsibilities", []))
                lines.append(f"| {resp.get('role', '')} | {resp.get('name', 'TBD')} | {resp_list} |")
        else:
            lines.append("*No responsibilities defined.*")
        lines.append("")

        # 12. Staffing and Training
        lines.append("## 12. Staffing and Training")
        lines.append("")
        lines.append(test_plan.staffing or "TBD")
        lines.append("")

        # 13. Schedule
        lines.append("## 13. Schedule")
        lines.append("")
        schedule = test_plan.schedule
        milestones = schedule.get("milestones", [])
        if milestones:
            lines.append("| Milestone | Target Date | Description |")
            lines.append("|-----------|-------------|-------------|")
            for ms in milestones:
                lines.append(f"| {ms.get('name', '')} | {ms.get('date', 'TBD')} | {ms.get('description', '')} |")
        else:
            lines.append("*No milestones defined.*")
        lines.append("")

        # 14. Risks and Contingencies
        lines.append("## 14. Risks and Contingencies")
        lines.append("")
        if test_plan.risks_contingencies:
            lines.append("| Risk | Probability | Impact | Mitigation | Contingency |")
            lines.append("|------|-------------|--------|------------|-------------|")
            for risk in test_plan.risks_contingencies:
                risk_text = risk.risk.replace("|", "\\|").replace("\n", " ")
                mitigation = risk.mitigation.replace("|", "\\|").replace("\n", " ")
                contingency = risk.contingency.replace("|", "\\|").replace("\n", " ")
                lines.append(f"| {risk_text} | {risk.probability} | {risk.impact} | {mitigation} | {contingency} |")
        else:
            lines.append("*No risks identified.*")
        lines.append("")

        # 15. Approvals
        lines.append("## 15. Approvals")
        lines.append("")
        if test_plan.approvals:
            lines.append("| Role | Name | Signature | Date |")
            lines.append("|------|------|-----------|------|")
            for appr in test_plan.approvals:
                lines.append(f"| {appr.role} | {appr.name} | {appr.signature} | {appr.date} |")
        else:
            lines.append("*No approvals recorded.*")
        lines.append("")

        # Footer
        lines.append("---")
        lines.append(f"*Generated on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')} by Jira Test Plan Generator*")
        lines.append(f"*Source: Jira Ticket {test_plan.identifier.replace('TP-', '')}*")

        return "\n".join(lines)

    def save(self, test_plan: TestPlan, filename: str = None) -> Path:
        """Render and save test plan to file."""
        if filename is None:
            key = test_plan.identifier.replace("TP-", "")
            filename = self.output_cfg.filename_template.format(key=key)

        filepath = self.output_dir / filename
        markdown = self.render(test_plan)

        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(markdown)

        return filepath

    def save_json(self, test_plan: TestPlan, filename: str = None) -> Path:
        """Save test plan as JSON."""
        if filename is None:
            key = test_plan.identifier.replace("TP-", "")
            filename = self.output_cfg.filename_template.replace('.md', '.json').format(key=key)

        filepath = self.output_dir / filename
        with open(filepath, 'w', encoding='utf-8') as f:
            json.dump(test_plan.to_json(), f, indent=2)

        return filepath